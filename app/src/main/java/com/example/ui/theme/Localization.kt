        val dynVal = getDynamicLessonTranslation(key, lang)
        if (dynVal != null) return dynVal

        val courseDict = courseTranslations[lang] ?: courseTranslations["en"]
        val courseValue = courseDict?.get(key)
        if (courseValue != null) return courseValue

        val suppDict = supplementaryTranslations[lang] ?: supplementaryTranslations["en"]
        val suppValue = suppDict?.get(key)
        if (suppValue != null) return suppValue

        val dict = translations[lang] ?: translations["en"]!!
        return dict[key] ?: translations["en"]!![key] ?: key
    }
